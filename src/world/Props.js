/** Uniform XZ grid of placed footprints — the cheap "did I already put something here". */
class FootprintGrid {
  constructor(cell = 2) {
    this.cell = cell;
    this.map = new Map();
  }
  _key(i, j) {
    return i * 8192 + j;
  }
  add(f) {
    const c = this.cell;
    const i0 = Math.floor((f.x - f.rx) / c);
    const i1 = Math.floor((f.x + f.rx) / c);
    const j0 = Math.floor((f.z - f.rz) / c);
    const j1 = Math.floor((f.z + f.rz) / c);
    for (let i = i0; i <= i1; i++) {
      for (let j = j0; j <= j1; j++) {
        const k = this._key(i, j);
        let list = this.map.get(k);
        if (!list) {
          list = [];
          this.map.set(k, list);
        }
        list.push(f);
      }
    }
  }
  /** True if `f` overlaps anything already in the grid (AABB in XZ plus a Y span test). */
  hits(f, pad = 0) {
    const c = this.cell;
    const i0 = Math.floor((f.x - f.rx - pad) / c);
    const i1 = Math.floor((f.x + f.rx + pad) / c);
    const j0 = Math.floor((f.z - f.rz - pad) / c);
    const j1 = Math.floor((f.z + f.rz + pad) / c);
    for (let i = i0; i <= i1; i++) {
      for (let j = j0; j <= j1; j++) {
        const list = this.map.get(this._key(i, j));
        if (!list) continue;
        for (const o of list) {
          if (Math.abs(o.x - f.x) > o.rx + f.rx + pad) continue;
          if (Math.abs(o.z - f.z) > o.rz + f.rz + pad) continue;
          if (o.y1 < f.y0 + 0.02 || o.y0 > f.y1 - 0.02) continue;
          return true;
        }
      }
    }
    return false;
  }
  clear() {
    this.map.clear();
  }
}

