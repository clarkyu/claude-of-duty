/**
 * Props.js — set dressing and clutter. Owner: props agent.
 * Files owned: this, world/props/**.
 * Publishes: `ctx.props`.
 *
 * ── What init() does ────────────────────────────────────────────────────────────
 *   1. Resolves the prop material palette from `ctx.materials` (world/props/materials.js).
 *   2. **Sweeps the world with raycasts** to discover where the ground, the roofs and
 *      the facades actually are. Nothing in here reads the level's data tables, so a
 *      building the level agent moves takes its rooftop water tank with it.
 *   3. Runs `props/placement.js`, which composes clusters with intent — rubbish in
 *      corners, crates at loading points, stalls along the plaza, vehicles nose-in to
 *      kerbs — instead of scattering uniformly.
 *   4. Each prop is generated by `props/catalog.js` into a **prop-local** accumulator,
 *      grounded onto the surface below it (aligned to the surface normal and sunk 15 mm
 *      so there is never a gap), overlap-tested against physics and against the props
 *      already placed, then merged into its district batch.
 *   5. Districts commit to one mesh per *resolved* material (several material keys alias
 *      onto one so the merged draw-call count stays inside the budget), wrapped in a
 *      THREE.LOD whose far level keeps the big silhouettes and replaces small clutter
 *      with box shells.
 *   6. Simplified colliders go to `ctx.physics` tagged with the correct §5 surface from
 *      `ctx.materials.surfaceOf`. Mid props get dynamic bodies with real mass; small
 *      debris gets none.
 *
 * ── Public API (ctx.props) ──────────────────────────────────────────────────────
 *   ready                       boolean
 *   root                        THREE.Group added to ctx.scene
 *   spawn(type, transform, opts)-> placed | null   (see PLACEMENT OPTIONS below)
 *   list(filter?)               -> placed[]        filter: type string or predicate
 *   count(type?)                -> number
 *   rebuild(seed?)              -> stats           tear down and re-place everything
 *   types()                     -> string[]        every spawnable type
 *   remove(placed)              -> boolean
 *   footprints()                -> [{x,z,rx,rz,y0,y1,type}]  large static blockers, for AI
 *   stats                       { props, draws, triangles, colliders, dynamic, buildMs }
 *
 * ── PLACEMENT OPTIONS (third argument, or folded into the transform) ────────────
 *   x, z            world position (required unless `pos` is given)
 *   pos             [x,y,z] | Vector3, overrides x/z
 *   y               height hint; with `raw` or `onWall` it is used verbatim
 *   yaw             radians about +Y
 *   scale           uniform scale
 *   lift            extra metres above the surface (stacking)
 *   raw             skip grounding entirely — the caller owns the transform
 *   onWall          mount flush to a wall; `normal` is the wall's outward normal
 *   onRoof          ground onto the roof under `y`, not the street
 *   static          force a dynamic type to be baked static
 *   seed            extra entropy for the per-prop RNG
 *   …plus anything the generator itself understands (damage, paint, count, …)
 *
 * ── Events ──────────────────────────────────────────────────────────────────────
 *   emits `props:ready`   { count, footprints, stats }
 *   emits `props:rebuilt` { count, seed }
 *   listens `quality:changed`
 */
